import type { ConnectionConfig } from "@/lib/backup/crypto";

export interface RestoreOptions {
  /**
   * Restoring into a throwaway test database on a different server (see
   * lib/backup/verify.ts). Ownership/permission statements that only make
   * sense on the original server — Postgres OWNER TO / GRANT / REVOKE, MySQL
   * DEFINER clauses — are left out, since those users won't exist there and
   * would fail the test for reasons that say nothing about the backup.
   */
  forTest?: boolean;
}

/**
 * Managing throwaway databases on the admin-configured test-restore server.
 * `server` connects to the server itself (its `database` is only a
 * maintenance database to connect to, e.g. "postgres"); names are always
 * generated by verify.ts and validated before use.
 */
export interface ScratchDatabaseOps {
  create(server: ConnectionConfig, name: string): Promise<void>;
  drop(server: ConnectionConfig, name: string): Promise<void>;
  /** Names of databases on the server starting with `prefix`. */
  list(server: ConnectionConfig, prefix: string): Promise<string[]>;
  /** Number of ordinary tables in the database `conn` points at. */
  countTables(conn: ConnectionConfig): Promise<number>;
}

export interface BackupEngine {
  /** Runs the native dump tool and writes a gzip-compressed dump to destPath. */
  dump(conn: ConnectionConfig, destPath: string): Promise<void>;
  /** Restores a gzip-compressed dump (as written by dump()) from srcPath into the target database. */
  restore(conn: ConnectionConfig, srcPath: string, options?: RestoreOptions): Promise<void>;
  /** Quick connectivity check used by the "test connection" UI action. */
  testConnection(conn: ConnectionConfig): Promise<{ ok: boolean; message?: string }>;
  /**
   * The last line a complete dump from this engine ends with — a dump
   * without it was cut short (tool killed, disk full, ...).
   */
  readonly completionMarker: RegExp;
  /** Counts the tables a dump creates (lines it'd run). Used to sanity-check a test restore. */
  readonly createTablePattern: RegExp;
  readonly scratch: ScratchDatabaseOps;
}
